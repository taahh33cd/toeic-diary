/** Tạo item Đồng nghĩa: ctx là câu trong bài, từ được hỏi đặt trong ==…== */
function dn(
  id: string,
  prompt: string,
  ctx: string,
  doc: string,
  vi: string,
  wrong: [string, string][],
  note: string,
): P7QItem {
  return {
    id,
    type: "dong-nghia",
    prompt,
    context: { label: "Câu trong bài", text: ctx },
    transLabel: LABEL,
    vi,
    wrong: wrong.map(([text, why]) => ({ text, error: "da-nghia" as const, why })),
    kwNote: KW,
    strategy: { options: OPTS, correct: "S5", why: S5_WHY },
    evidence: { doc, excerpt: ctx, note },
  };
}

