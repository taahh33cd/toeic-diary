import type { P7QItem, StrategyCode, TransError } from "../types";

const OPTS: StrategyCode[] = ["S7", "S2", "S3", "S1"];

/**
 * Tạo item Liên kết văn bản. `key` mô tả chìa khoá (thông tin tra chéo);
 * `ctx` là 2 đoạn trích từ 2 văn bản, ngăn bởi ‖.
 */
function lk(
  id: string,
  prompt: string,
  vi: string,
  wrong: [string, TransError, string][],
  kwNote: string,
  why: string,
  doc: string,
  ctx: string,
  note: string,
): P7QItem {
  return {
    id,
    type: "lien-ket",
    prompt,
    vi,
    wrong: wrong.map(([text, error, w]) => ({ text, error, why: w })),
    kwNote,
    strategy: { options: OPTS, correct: "S7", why },
    evidence: { doc, excerpt: ctx, note },
  };
}

